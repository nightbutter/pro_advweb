/**
 * Single source of truth for the runtime schema used by initDatabase().
 *
 * The canonical migration files (server/migrations/*.sql) are applied by
 * scripts/migrate.ts for explicit upgrades. initDatabase() cannot read those
 * files at runtime on serverless (they are not bundled), so it executes this
 * module instead. test/migrations.test.ts asserts both produce an identical
 * schema fingerprint and that the file contents match these constants, so the
 * two paths can never drift silently.
 */

// Mirrors server/migrations/001_init.sql
export const INIT_SCHEMA_SQL = `
CREATE TABLE IF NOT EXISTS customers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  address TEXT NOT NULL,
  lat DOUBLE PRECISION NOT NULL,
  lng DOUBLE PRECISION NOT NULL,
  zone TEXT NOT NULL DEFAULT 'ขามเรียง'
    CHECK(zone IN ('ขามเรียง', 'ท่าขอนยาง', 'หน้าป้าย'))
);

CREATE TABLE IF NOT EXISTS orders (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "orderNumber" TEXT NOT NULL UNIQUE,
  "customerId" INTEGER NOT NULL,
  "boxCount" INTEGER NOT NULL CHECK("boxCount" >= 1 AND "boxCount" <= 3),
  "orderTime" TEXT DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')),
  status TEXT DEFAULT 'pending',
  "assignedRiderId" INTEGER,
  "deliverySequence" INTEGER,
  FOREIGN KEY("customerId") REFERENCES customers(id)
);

CREATE INDEX IF NOT EXISTS idx_orders_customer ON orders("customerId");
CREATE INDEX IF NOT EXISTS idx_orders_rider ON orders("assignedRiderId");

CREATE TABLE IF NOT EXISTS riders (
  id INTEGER PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  color TEXT NOT NULL,
  "maxOrders" INTEGER DEFAULT 3,
  status TEXT DEFAULT 'active'
);

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  "passwordHash" TEXT NOT NULL,
  role TEXT NOT NULL CHECK(role IN ('admin', 'rider')),
  "riderId" INTEGER REFERENCES riders(id)
);
`;

// Mirrors server/migrations/002_order_number_seq.sql
export const ORDER_NUMBER_SEQ_SQL = `
CREATE SEQUENCE IF NOT EXISTS order_number_seq;
`;

// Mirrors server/migrations/003_customer_registration.sql
export const CUSTOMER_REGISTRATION_SQL = `
ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check;
ALTER TABLE users ADD CONSTRAINT users_role_check CHECK(role IN ('admin', 'rider', 'customer'));

CREATE UNIQUE INDEX IF NOT EXISTS idx_users_lower_username ON users (LOWER(username));

CREATE TABLE IF NOT EXISTS customer_profiles (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId" INTEGER NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  address TEXT NOT NULL,
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
`;

export const SCHEMA_SQL = `${INIT_SCHEMA_SQL}\n${ORDER_NUMBER_SEQ_SQL}\n${CUSTOMER_REGISTRATION_SQL}`;
