-- 001_init.sql
-- Initial schema for Smart Rider Route Planning (PostgreSQL / Neon)
-- Ported from the previous SQLite schema (server/src/database/connection.ts).
-- Column names stay camelCase (quoted) to preserve the existing JSON API contract.

CREATE TABLE IF NOT EXISTS customers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  address TEXT NOT NULL,
  lat DOUBLE PRECISION NOT NULL,
  lng DOUBLE PRECISION NOT NULL,
  zone TEXT NOT NULL DEFAULT 'ขามเรียง'
    CHECK(zone IN ('ขามเรียง', 'ท่าขอนยาง', 'หน้าป้าย'))
);

CREATE TABLE IF NOT EXISTS orders (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "orderNumber" TEXT NOT NULL UNIQUE,
  "customerId" INTEGER NOT NULL,
  "boxCount" INTEGER NOT NULL CHECK("boxCount" >= 1 AND "boxCount" <= 3),
  "orderTime" TEXT DEFAULT (to_char(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')),
  status TEXT DEFAULT 'pending',
  "assignedRiderId" INTEGER,
  "deliverySequence" INTEGER,
  FOREIGN KEY("customerId") REFERENCES customers(id)
);

CREATE INDEX IF NOT EXISTS idx_orders_customer ON orders("customerId");
CREATE INDEX IF NOT EXISTS idx_orders_rider ON orders("assignedRiderId");

CREATE TABLE IF NOT EXISTS riders (
  id INTEGER PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  color TEXT NOT NULL,
  "maxOrders" INTEGER DEFAULT 3,
  status TEXT DEFAULT 'active'
);

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE,
  "passwordHash" TEXT NOT NULL,
  role TEXT NOT NULL CHECK(role IN ('admin', 'rider')),
  "riderId" INTEGER REFERENCES riders(id)
);
